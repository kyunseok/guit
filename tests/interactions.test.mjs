import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import test from 'node:test';
import { initializeReservations } from '../src/reservations.js';
import { koreaInput } from '../src/reservation-rules.js';
import { renderSetlist } from '../src/setlist-view.js';
test('reservation controls and song feedback preserve their interaction contracts', async () => {
const dom = new JSDOM(await readFile(new URL('../index.html', import.meta.url), 'utf8'), { url: 'https://example.test/#room-reservation/list', pretendToBeVisual: true });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
window.matchMedia = () => ({ matches: true, addEventListener() {} });
window.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
window.HTMLDialogElement.prototype.close = function() { this.open = false; };
const $ = id => document.getElementById(id);
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const calls = [];
const day = koreaInput().slice(0, 10);
const booking = { id: 'test', starts_at: day + 'T18:00:00+09:00', ends_at: day + 'T19:00:00+09:00', user_name: '테스트', purpose: '합주연습', people: 3, has_password: true };
let rows = [booking];
const api = { reservationsList: async(from, to) => { calls.push(['list', from, to]); return rows; }, fixedReservationsList: async() => [], reservationCancel: async(id, password) => { calls.push(['cancel', id, password]); if (password !== 'test-only') return 'invalid_password'; rows = []; return 'cancelled'; }, reservationSubmit: async(value) => { calls.push(['submit', value]); } };
const controller = initializeReservations(() => api);
controller.show(true, 'list'); controller.connect(); await tick();
assert.equal($('reservation-view-day').getAttribute('aria-pressed'), 'true');
assert.equal(Date.parse(calls[0][2]) - Date.parse(calls[0][1]), 86400000);
assert.equal(document.querySelectorAll('.reservation-summary').length, 1);
document.querySelector('.reservation-summary').click();
assert.equal($('reservation-detail').open, true);
document.querySelector('.reservation-cancel').click();
assert.equal(calls.some(call => call[0] === 'cancel'), false);
const pwd = document.querySelector('.reservation-cancel-form input');
pwd.value = 'wrong';
document.querySelector('.reservation-cancel-form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })); await tick();
assert.match(document.querySelector('.reservation-cancel-message').textContent, /일치하지/);
pwd.value = 'test-only';
document.querySelector('.reservation-cancel-form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })); await tick(); await tick();
assert.equal($('reservation-detail').open, false);
assert.equal(document.querySelectorAll('.reservation-summary').length, 0);
rows = [{...booking, has_password:false}]; $('reservation-refresh').click(); await tick();
document.querySelector('.reservation-summary').click(); document.querySelector('.reservation-cancel').click(); await tick();
assert.deepEqual(calls.filter(call => call[0] === 'cancel').at(-1), ['cancel','test','']);
rows = [{...booking, is_fixed:true}]; $('reservation-detail').close(); $('reservation-refresh').click(); await tick();
document.querySelector('.reservation-summary').click();
assert.equal(document.querySelector('#reservation-detail .reservation-cancel'), null);
$('reservation-detail').close();
$('reservation-view-list').click(); await tick();
assert.equal($('reservation-month-toolbar').hidden, false);
assert.equal($('reservation-date-toolbar').hidden, true);
assert.equal(document.querySelectorAll('.reservation-day-heading').length, 1);
controller.show(true, 'book');
$('reservation-book-date').value='2099-12-31'; $('reservation-start').value='23:30'; $('reservation-end').value='00:30';
$('reservation-end').dispatchEvent(new window.Event('change'));
assert.match($('reservation-time-help').textContent, /다음 날 01\/01 종료/);
$('reservation-user').value='테스트'; $('reservation-purpose').value='합주연습'; $('reservation-people').value='3';
$('reservation-form').dispatchEvent(new window.Event('submit', {bubbles:true,cancelable:true})); await tick();
assert.equal(calls.find(call => call[0] === 'submit')[1].ends_at, '2100-01-01T00:30:00+09:00');
const feedback=[];
const result = renderSetlist({headers:['구분','곡명','가수','기타'],rows:[['1조','곡 A','가수 A','https://example.test/'],['2조','곡 A','가수 B','<script>alert(1)</script>']]}, {songColumn:1,feedbackTitle:'정기공연 · 1차리허설',sheetUrl:'https://docs.google.com/spreadsheets/d/test/edit?gid=42'}, async(song)=>feedback.push(song));
document.body.append(result.root);
assert.equal(result.count, 2);
assert.equal(result.root.querySelectorAll('script').length, 0);
assert.equal(result.root.querySelectorAll('th')[0].textContent, '곡명');
result.root.querySelectorAll('.song-feedback-action')[1].click();
result.root.querySelectorAll('.song-feedback-link')[1].click(); await tick();
assert.deepEqual(feedback[0],feedback[1]);
assert.equal(feedback[0].group,'2조');
assert.match(feedback[0].sheetUrl,/gid=42/);
result.root.querySelectorAll('.setlist-view-options button')[1].click();
assert.equal(result.root.classList.contains('show-table'),true);
dom.window.close();
});
